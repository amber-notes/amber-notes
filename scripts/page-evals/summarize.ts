// Page evals: the results table (results/RESULTS.md) from every round's saved sessions.
//   deno run -A scripts/page-evals/summarize.ts [round ...]
const dir = new URL("results/", import.meta.url);
type R = { task: string; model: string; round: string; skill: boolean; score: number; passed: number; total: number; tool_calls: number; tool_errors: number; usd: number; usage: { input: number; output: number; cacheRead: number; cacheWrite: number }; checks: { name: string; pass: boolean; detail?: string }[] };

const rounds: string[] = Deno.args.length ? Deno.args : [...Deno.readDirSync(dir)].filter((e) => e.isDirectory).map((e) => e.name).sort();
const all = new Map<string, R[]>();
for (const r of rounds) {
  const list: R[] = [];
  for (const e of Deno.readDirSync(new URL(`${r}/`, dir))) if (e.name.endsWith(".json")) list.push(JSON.parse(Deno.readTextFileSync(new URL(`${r}/${e.name}`, dir))));
  all.set(r, list);
}
const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
const mean = (xs: number[]) => xs.reduce((s, x) => s + x, 0) / (xs.length || 1);
const tasks = [...new Set([...all.values()].flat().map((r) => r.task))].sort();
// Variants within a round: model and skill.
const variant = (r: R) => `${r.model.replace("claude-", "")}${r.skill ? "+skill" : ""}`;
const cols = [...all].flatMap(([round, list]) => [...new Set(list.map(variant))].map((v) => ({ round, v, list: list.filter((r) => variant(r) === v) })));

let md = `# Note page evals\n\nGenerated by scripts/page-evals/summarize.ts. Each cell is the share of checks passed for one session (generic page checks plus the task's own). Tasks a round didn't run are blank.\n\n`;
md += `| Round | Model | Tasks | Mean score | All checks passed | Tool calls (mean) | Failed tool calls | Output tokens (mean) | Cost |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n`;
for (const c of cols) {
  md += `| ${c.round} | ${c.v} | ${c.list.length} | ${pct(mean(c.list.map((r) => r.score)))} | ${c.list.filter((r) => r.passed === r.total).length}/${c.list.length} | ${mean(c.list.map((r) => r.tool_calls)).toFixed(1)} | ${c.list.reduce((s, r) => s + r.tool_errors, 0)} | ${Math.round(mean(c.list.map((r) => r.usage.output)))} | $${c.list.reduce((s, r) => s + r.usd, 0).toFixed(2)} |\n`;
}
md += `\n## Per task\n\n| Task | ${cols.map((c) => `${c.round} ${c.v}`).join(" | ")} |\n| --- | ${cols.map(() => "---").join(" | ")} |\n`;
for (const t of tasks) {
  md += `| ${t} | ${cols.map((c) => { const r = c.list.find((x) => x.task === t); return r ? `${Math.round(r.score * 100)}% (${r.tool_calls})` : ""; }).join(" | ")} |\n`;
}
md += `\nIn parentheses: tool calls.\n\n## Failed checks\n\n`;
for (const c of cols) {
  const fails = c.list.flatMap((r) => r.checks.filter((k) => !k.pass).map((k) => `${r.task}: ${k.name}${k.detail ? ` (${String(k.detail).slice(0, 110).replace(/\|/g, "/").replace(/\n/g, " ")})` : ""}`));
  md += `### ${c.round} ${c.v}\n\n${fails.length ? fails.map((f) => `- ${f}`).join("\n") : "None."}\n\n`;
}
const spend = Deno.readTextFileSync(new URL("spend.jsonl", dir)).split("\n").filter(Boolean).map((l) => JSON.parse(l));
md += `## Spend\n\n${spend.length} model sessions, $${spend.reduce((s, x) => s + x.usd, 0).toFixed(2)} in all (results/spend.jsonl).\n`;
Deno.writeTextFileSync(new URL("RESULTS.md", dir), md);
