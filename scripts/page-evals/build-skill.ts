// Writes what's generated from one source, so the server, the skill and the templates can't drift:
// - supabase/functions/mcp/page_templates.gen.ts from plugins/amber-notes/skills/note-pages/templates/*.html
// - plugins/amber-notes/skills/note-pages/references/guide.md from PAGE_GUIDE (page_guide.ts)
//   deno run -A scripts/page-evals/build-skill.ts [--check]
const root = new URL("../../", import.meta.url);
const skill = new URL("plugins/amber-notes/skills/note-pages/", root);
const check = Deno.args.includes("--check");

const templates: { name: string; description: string; expects: string; html: string }[] = [];
for await (const e of Deno.readDir(new URL("templates/", skill))) {
  if (!e.name.endsWith(".html")) continue;
  const html = await Deno.readTextFile(new URL(`templates/${e.name}`, skill));
  const m = html.match(/<!-- template: ([\w-]+) \| (.+?) \| (.+?) -->/);
  if (!m) throw new Error(`${e.name}: no <!-- template: name | description | expects --> line`);
  if (`${m[1]}.html` !== e.name) throw new Error(`${e.name}: the template line names ${m[1]}`);
  templates.push({ name: m[1], description: m[2], expects: m[3], html });
}
templates.sort((a, b) => a.name.localeCompare(b.name));

const gen = `// Generated by scripts/page-evals/build-skill.ts from plugins/amber-notes/skills/note-pages/templates/. Don't edit.
export const PAGE_TEMPLATES: { name: string; description: string; expects: string; html: string }[] = ${JSON.stringify(templates, null, 2)};
`;
const genPath = new URL("supabase/functions/mcp/page_templates.gen.ts", root);
const write = async (path: URL, text: string) => {
  const now = await Deno.readTextFile(path).catch(() => "");
  if (now === text) return;
  if (check) throw new Error(`${path.pathname} is out of date: run deno run -A scripts/page-evals/build-skill.ts`);
  await Deno.writeTextFile(path, text);
  console.log("wrote", path.pathname.replace(root.pathname, ""));
};
await write(genPath, gen);

// The guide imports the generated templates, so it's read after they're written.
const { PAGE_GUIDE, PAGE_INSTRUCTIONS } = await import(new URL("supabase/functions/mcp/page_guide.ts", root).href + `?v=${Date.now()}`);
const stamp = "<!-- Generated from supabase/functions/mcp/page_guide.ts by scripts/page-evals/build-skill.ts. Don't edit. -->";
await Deno.mkdir(new URL("references/", skill), { recursive: true });
await write(new URL("references/guide.md", skill), `${stamp}\n${PAGE_GUIDE}`);

// The Claude skill: when to use it, the rules every client gets from the server, and the guide.
const description = "Build, change, check and fill the apps in Amber Notes notes (a note's App side: habit trackers, budgets, reading or workout logs, CRMs, trip plans, flashcards, dashboards) through the amber-notes MCP server, and put data into them: rows, records, settings, files. Use when the person asks to make a note an app, change or fix a note's app, add or import data to it, or set up an API key for one.";
await write(new URL("SKILL.md", skill), `---
name: note-pages
description: ${description}
---
${stamp}

# Apps in Amber Notes notes

${PAGE_INSTRUCTIONS}

Read \`references/guide.md\` before building or changing an app: the window.amber contract, where data lives, design and accessibility, API keys, the check-before-done loop and a starter. \`templates/\` holds tested apps to start from; the server serves the same guide and templates through \`get_page_guide\`, so nothing here is needed for the tools to work.
`);

// The same rules for Codex, Cursor and other agents that read AGENTS.md.
await write(new URL("plugins/amber-notes/AGENTS.md", root), `${stamp}

# Amber Notes apps (for AGENTS.md)

Paste this into a project's AGENTS.md (Codex, Cursor and other agents read it) when you use the Amber Notes MCP server (https://mcp.ambernotes.app) there. The server already teaches all of this through its instructions and \`get_page_guide\`; this keeps it in front of agents that skim server instructions.

${PAGE_INSTRUCTIONS}
`);
