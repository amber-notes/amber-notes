// Writes supabase/functions/mcp/tailwind.gen.ts: the stylesheets a project's `@import "tailwindcss"`
// (and shadcn's `@import "tw-animate-css"`) resolve to when the server compiles its CSS, so the
// edge function needs no network or node_modules for them.
//   deno run -A scripts/page-evals/build-tailwind.ts
const TAILWIND = "4.1.14", ANIMATE = "1.4.0";
const get = async (url: string) => { const r = await fetch(url); if (!r.ok) throw new Error(`${url}: ${r.status}`); return await r.text(); };
const sheets = {
  tailwindcss: await get(`https://cdn.jsdelivr.net/npm/tailwindcss@${TAILWIND}/index.css`),
  "tw-animate-css": await get(`https://cdn.jsdelivr.net/npm/tw-animate-css@${ANIMATE}/dist/tw-animate.css`),
};
await Deno.writeTextFile(new URL("../../supabase/functions/mcp/tailwind.gen.ts", import.meta.url),
  `// Generated by scripts/page-evals/build-tailwind.ts (tailwindcss ${TAILWIND}, tw-animate-css ${ANIMATE}). Don't edit.\nexport const TAILWIND_VERSION = "${TAILWIND}";\nexport const STYLESHEETS: Record<string, string> = ${JSON.stringify(sheets)};\n`);
console.log("wrote tailwind.gen.ts", Object.fromEntries(Object.entries(sheets).map(([k, v]) => [k, v.length])));
